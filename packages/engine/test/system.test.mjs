test('the loud fixture breaks constraints and is balanced, quoting each principle', { timeout: 60000 }, async () => {
  const loud = await designSystem({ brand: fixture('loud') });
  assertValid(loud);
  const raw = Object.fromEntries(AXIS_IDS.map((a) => [a, loud.measured.brand.axes[a].value]));
  assert.ok(validateAxes(raw).some((v) => v.code === 'constraint'), 'the raw measurement must break a constraint');
  const moved = AXIS_IDS.filter((a) => loud.axisNotes[a].moved);
  assert.ok(moved.length >= 2, `expected moves, got ${moved}`);
  for (const a of moved) {
    const m = loud.axisNotes[a].moved;
    assert.ok(m.because.length, `${a} moved without a reason`);
    for (const b of m.because) assert.equal(b.principle, taxonomy.constraints.find((c) => c.id === b.constraint).principle);
    assert.ok(loud.notes.some((n) => n.startsWith(`Balance: ${a} moved`)));
  }
  assert.equal(loud.axes['type-expression'], 1, 'the loud type is kept and the color quiets down');
  assert.equal(loud.axisNotes['color-restraint'].moved.because[0].constraint, 'loud-type-quiet-color');
});

