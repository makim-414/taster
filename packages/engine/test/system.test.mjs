test('tuning roundness or density to an extreme moves the other axis and says why', () => {
  const base = composeSystem({});
  const round = tuneSystem(base, { roundness: 1 });
  assert.equal(round.axes.roundness, 1);
  assert.equal(round.axes.elevation, 0.5);
  assert.deepEqual(round.axisNotes.elevation.moved.because.map((b) => b.constraint), ['material-band-radius']);
  assert.ok(round.tuned.at(-1).summary.some((l) => l.includes('Radius and depth describe one material')));
  assert.equal(round.tokens['--r-card'], '20px');
  assert.notEqual(round.tokens['--sh-card'], base.tokens['--sh-card']);
  assertValid(round);

  const dense = tuneSystem(base, { density: 1 });
  assert.equal(dense.axes.density, 1);
  assert.equal(dense.axes['type-expression'], 0.25);
  assert.equal(dense.axes.motion, 0.25);
  assert.equal(dense.axisNotes['type-expression'].moved.because[0].constraint, 'dense-screens-quiet-type');
  assert.equal(dense.axisNotes.motion.moved.because[0].constraint, 'dense-screens-move-less');
  assertValid(dense);

  // A move inside the constraints moves nothing else.
  const calm = tuneSystem(base, { stroke: 0.5 });
  assert.deepEqual(calm.tuned.at(-1).moved, {});
  assert.deepEqual(calm.tuned.at(-1).summary, ['stroke set to light (0.5) by the builder', 'no other axis had to move']);
});

test('negative controls: invalid settings are rejected', () => {
  const base = composeSystem({});
  assert.throws(() => tuneSystem(base, { roundness: 2 }), /outside 0\.\.1/);
  assert.throws(() => tuneSystem(base, { wobble: 1 }), /Unknown axis wobble/);
  assert.throws(() => tuneSystem(base, { density: Number.NaN }), /finite number/);
  assert.throws(() => tuneSystem(base, {}), /at least one axis/);
  assert.throws(() => composeSystem({ intent: { axes: { contrast: -1 } } }), /outside 0\.\.1/);
  assert.throws(() => composeSystem({ intent: { axes: { density: 1, 'type-expression': 1 } } }), /dense-screens-quiet-type/);
  // Pillow corners need some depth, heavy borders forbid it: no third axis can reconcile them.
  assert.throws(() => composeSystem({ intent: { axes: { roundness: 1, stroke: 1 } } }), /cannot all hold together/);
  assert.throws(() => composeSystem({ intent: { surface: 'spaceship' } }), /Unknown surface/);
  // A saved system whose axes were edited off balance is refused, not silently repaired.
  assert.throws(() => tuneSystem({ ...base, axes: { ...base.axes, density: 1, 'type-expression': 1 } }, { stroke: 0.5 }), /not valid/);
  assert.throws(() => systemForCategory(base, 'spaceship'), /Unknown category/);
});

test('every generated system keeps text at AA or better', () => {
  const brands = [null, '#4c1d95', '#facc15', '#16a34a', '#ffffff', '#0f766e', '#ff7a00'];
  let pairs = 0;
  for (const scheme of ['dark', 'light']) {
    for (const color of brands) {
      const identity = color ? { tokens: brandTheme({ brand: { color, dark: scheme === 'dark' } }).tokens } : null;
      for (const axis of AXIS_IDS) {
        for (const v of STEPS[axis]) {
          const settings = balance({ ...DEFAULTS, [axis]: v }, axis);
          const report = contrastReport(systemTokens(settings, { scheme, identity }), scheme).filter((p) => p.text !== '--accent-fg');
          pairs += report.length;
          for (const p of report) assert.ok(p.ratio >= 4.5, `${scheme} ${color} ${axis}=${v}: ${p.text} on ${p.surface} ${p.ratio}`);
        }
      }
    }
  }
  assert.ok(pairs > 1000);
});

