const shipped = Object.fromEntries([...TOKENS_CSS.slice(0, TOKENS_CSS.indexOf('@media')).matchAll(/^\s*(--[\w-]+):\s*([^;]+);/gm)].map((m) => [m[1], m[2].trim()]));

// Reads a token value the way the browser would compare it: calc() over --radius resolved, numbers normalized.
function norm(value) {
  const calc = String(value).match(/^calc\(var\(--radius\) \* ([\d.]+)\)$/);
  if (calc) return `${Number((10 * Number(calc[1])).toFixed(2))}px`;
  if (value === 'var(--radius)') return '10px';
  return String(value).replace(/\d*\.?\d+/g, (n) => String(Number(n))).replace(/\s+/g, '');
}
const assertValid = (system) => assert.deepEqual(validateAxes(system.axes), [], 'every system passes validateAxes');

const SHARP = { density: 1, contrast: 0.75, roundness: 0, 'type-expression': 0, 'color-restraint': 1, elevation: 0, motion: 0, stroke: 0.75 };
const AIRY = { density: 0, contrast: 0.5, roundness: 0.75, 'type-expression': 0.5, 'color-restraint': 1, elevation: 0.5, motion: 0.75, stroke: 0 };

test('default axes reproduce the shipped tokens exactly', () => {
  const system = composeSystem({});
  assert.deepEqual(system.axes, DEFAULTS);
  for (const axis of taxonomy.axes) {
    for (const prop of axis.drives) {
      assert.ok(prop in system.tokens, `${prop} missing`);
      assert.equal(norm(system.tokens[prop]), norm(shipped[prop]), `${prop}: ${system.tokens[prop]} vs ${shipped[prop]}`);
    }
  }
  assert.match(system.css, /^\/\* Design system generated by Taster[\s\S]*\n:root, :root\[data-theme\] \{[\s\S]*@media \(prefers-reduced-motion: reduce\)/);
  assert.doesNotMatch(system.css, /\.theme-dark/, 'no brand read, so nested scopes keep the shipped look');
});

test('a brand system beats the light theme at the root and keeps its identity in nested scopes', { timeout: 90000 }, async () => {
  const browser = await launch();
  try {
    const read = await readPage(browser, fixture('fonts-docs'));
    const s = composeSystem({ brand: read, intent: { axes: { roundness: 1 } } });
    assert.match(s.css, /\n\.theme-dark, \.theme-light \{[^}]*--brand: /);
    const light = readFileSync(new URL('../../registry/src/themes/light.css', import.meta.url), 'utf8');
    const page = await browser.newPage();
    await page.setContent(`<html data-theme="light"><head><style>${TOKENS_CSS}\n${light}\n${s.css}</style></head><body><div class="theme-dark" id="nested"></div></body></html>`);
    await page.emulateMedia({ reducedMotion: 'reduce' });
    const read2 = await page.evaluate(() => {
      const get = (el, k) => getComputedStyle(el).getPropertyValue(k).trim();
      const root = document.documentElement, nested = document.getElementById('nested');
      return { rootBrand: get(root, '--brand'), rootCard: get(root, '--r-card'), nestedBrand: get(nested, '--brand'), nestedFont: get(nested, '--font'), press: get(root, '--dur-press') };
    });
    // Reduced motion still wins over the axis durations on a page that sets data-theme.
    assert.equal(read2.press, '1ms');
    // Negative control: with a plain :root, the light theme's ink --brand won at the root and .theme-dark reset it.
    assert.equal(read2.rootBrand, s.tokens['--brand']);
    assert.equal(read2.rootCard, s.tokens['--r-card']);
    assert.equal(read2.nestedBrand, s.tokens['--brand']);
    assert.equal(read2.nestedFont, s.tokens['--font']);
  } finally {
    await browser.close();
  }
});

test('every axis step writes every token it drives, and only changes those', () => {
  const base = systemTokens(DEFAULTS);
  for (const axis of AXIS_IDS) {
    for (const v of STEPS[axis]) {
      const settings = balance({ ...DEFAULTS, [axis]: v }, axis);
      const t = systemTokens(settings);
      for (const prop of taxonomy.axes.find((a) => a.id === axis).drives) assert.ok(t[prop] != null && t[prop] !== 'undefined', `${axis}=${v} ${prop}`);
      if (Object.entries(settings).every(([a, x]) => a === axis || x === DEFAULTS[a])) {
        const driven = new Set(taxonomy.axes.find((a) => a.id === axis).drives);
        for (const [k, val] of Object.entries(t)) if (!driven.has(k)) assert.equal(val, base[k], `${axis}=${v} changed ${k}`);
      }
    }
  }
});

