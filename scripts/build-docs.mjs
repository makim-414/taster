// Derives cross links from pattern frontmatter, writes rules/RULES.md and patterns/README.md,
// and copies data into the skill bundle. Run after editing patterns, rules or the registry.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, SKILL_DATA, readJson, writeJson, loadPatterns, bundleFiles } from './lib.mjs';
import { renderAll } from '../engine/exports.mjs';
import { extensionRules } from './lib.mjs';

const patterns = loadPatterns().map((p) => p.data).filter(Boolean);
const taxonomy = readJson('taxonomy/taxonomy.json');
const rules = readJson('rules/rules.json');
const registry = readJson('registry/registry.json');

// rules.fix_patterns <- patterns.replaces
for (const r of rules.rules) {
  r.fix_patterns = patterns.filter((p) => (p.replaces || []).includes(r.id)).map((p) => p.id).sort();
}
writeJson('rules/rules.json', rules);

// registry.patterns <- patterns.components
for (const c of registry.components) {
  c.patterns = patterns.filter((p) => (p.components || []).includes(c.id)).map((p) => p.id).sort();
}
writeJson('registry/registry.json', registry);

// rules/RULES.md
const byId = Object.fromEntries(patterns.map((p) => [p.id, p]));
const level = { deterministic: 'auto', heuristic: 'auto, needs review', manual: 'by eye' };
let md = '# Slop rules\n\nGenerated by scripts/build-docs.mjs from rules/rules.json. Do not edit by hand.\n\n';
md += `${rules.rules.length} rules. "auto" rules are checked by rules/detect.js in a real browser.\n\n`;
md += '| Id | Rule | Check | Fix with |\n|---|---|---|---|\n';
for (const r of rules.rules) {
  const fixes = r.fix_patterns.map((id) => `[${byId[id]?.name || id}](../patterns/${id}.md)`).join(', ');
  md += `| ${r.id} | ${r.name} | ${level[r.detect.level] || r.detect.level} | ${fixes} |\n`;
}
fs.writeFileSync(path.join(ROOT, 'rules/RULES.md'), md);

// patterns/README.md grouped by family -> category
const catName = Object.fromEntries(taxonomy.categories.map((c) => [c.id, c.name]));
let pm = '# Patterns\n\nGenerated by scripts/build-docs.mjs. Grouped by family and category.\n\n';
for (const fam of taxonomy.families) {
  const inFam = patterns.filter((p) => fam.categories.includes(p.category));
  if (!inFam.length) continue;
  pm += `## ${fam.name}\n\n${fam.summary}\n\n`;
  for (const cat of fam.categories) {
    const list = inFam.filter((p) => p.category === cat);
    if (!list.length) continue;
    pm += `### ${catName[cat] || cat}\n\n`;
    for (const p of list) pm += `- [${p.name}](${p.id}.md)${p.replaces?.length ? ` fixes ${p.replaces.join(', ')}` : ''}\n`;
    pm += '\n';
  }
}
fs.writeFileSync(path.join(ROOT, 'patterns/README.md'), pm);

// README taxonomy block: one row per family with its categories and pattern count.
const readmePath = path.join(ROOT, 'README.md');
const readme = fs.readFileSync(readmePath, 'utf8');
let block = `${patterns.length} patterns, ${rules.rules.length} rules, ${registry.components.length} components, `;
block += `${taxonomy.uses.length} uses, ${taxonomy.surfaces.length} surfaces.\n\n| Family | Categories | Patterns |\n|---|---|---|\n`;
for (const fam of taxonomy.families) {
  const n = patterns.filter((p) => fam.categories.includes(p.category)).length;
  block += `| ${fam.name} | ${fam.categories.map((c) => catName[c] || c).join(', ')} | ${n} |\n`;
}
const start = '<!-- taxonomy:start -->', end = '<!-- taxonomy:end -->';
if (readme.includes(start) && readme.includes(end)) {
  const next = readme.slice(0, readme.indexOf(start) + start.length) + '\n' + block + readme.slice(readme.indexOf(end));
  fs.writeFileSync(readmePath, next);
}

// exports/: the rules as instruction files for agents without MCP (AGENTS.md, Cursor, Windsurf, Cline, Copilot,
// Gemini, Claude). Rendered after rules.json is rewritten above, so the fix lines stay current.
for (const [rel, content] of Object.entries(renderAll())) {
  fs.mkdirSync(path.dirname(path.join(ROOT, rel)), { recursive: true });
  fs.writeFileSync(path.join(ROOT, rel), content);
}

// extension/: the detector and the rule names next to the overlay, so the extension and the bookmarklet
// (served by web/app/taster) inject the same files.
fs.copyFileSync(path.join(ROOT, 'rules/detect.js'), path.join(ROOT, 'extension/detect.js'));
fs.writeFileSync(path.join(ROOT, 'extension/rules.js'), extensionRules(rules.rules));

// Skill bundle
fs.rmSync(SKILL_DATA, { recursive: true, force: true });
for (const [src, dst] of bundleFiles()) {
  fs.mkdirSync(path.dirname(path.join(ROOT, dst)), { recursive: true });
  fs.copyFileSync(path.join(ROOT, src), path.join(ROOT, dst));
}
console.log(`BUILD OK patterns=${patterns.length} rules=${rules.rules.length} components=${registry.components.length}`);
